#!/usr/bin/env python3
"""
Cleanup script for scientifically invalid sweep results.

This script identifies sweep directories with inadequate time horizons
and recommends which ones to keep versus remove based on scientific validity.
"""

import json
from pathlib import Path
import shutil
from datetime import datetime


def identify_invalid_sweeps(base_path: Path) -> dict:
    """Identify sweep directories with scientifically invalid parameters."""
    sweep_dirs = list(base_path.glob("profile_sweep_quick_*"))
    
    invalid_sweeps = []
    valid_sweeps = []
    
    for sweep_dir in sweep_dirs:
        print(f"Evaluating: {sweep_dir.name}")
        
        # Check if this directory has any valid files
        valid_files = 0
        invalid_files = 0
        total_size = 0
        
        for json_file in sweep_dir.glob("t3_sweep_*.json"):
            try:
                with open(json_file, 'r') as f:
                    data = json.load(f)
                
                # Estimate time horizon (based on our analysis, most are using 10s)
                # For scientific validity, we need at least 3600s (1 hour) for rare events
                time_horizon = 10.0  # Default conservative estimate
                
                # Check if the file is complete
                if 'cascade_probabilities' in data and len(data['cascade_probabilities']) > 0:
                    file_size = json_file.stat().st_size
                    total_size += file_size
                    
                    # Determine validity based on time horizon and completeness
                    is_valid = time_horizon >= 3600.0  # At least 1 hour for rare event statistics
                    if is_valid:
                        valid_files += 1
                    else:
                        invalid_files += 1
                else:
                    invalid_files += 1
                    
            except json.JSONDecodeError:
                invalid_files += 1  # Mark as invalid if JSON is malformed
            except Exception:
                invalid_files += 1  # Mark as invalid for any other error
        
        # Determine if this directory should be kept
        directory_info = {
            'path': sweep_dir,
            'name': sweep_dir.name,
            'valid_files': valid_files,
            'invalid_files': invalid_files,
            'total_size_kb': round(total_size / 1024, 2),
            'timestamp': sweep_dir.name.split("_", 3)[-1] if "_" in sweep_dir.name else "unknown"
        }
        
        # Mark as invalid if all files are invalid or time horizon is inadequate
        if invalid_files > 0 or valid_files == 0:
            invalid_sweeps.append(directory_info)
        else:
            valid_sweeps.append(directory_info)
    
    return {
        'invalid_sweeps': invalid_sweeps,
        'valid_sweeps': valid_sweeps
    }


def recommend_cleanup_actions(invalid_sweeps: list, valid_sweeps: list):
    """Recommend cleanup actions based on scientific validity."""
    print("\n" + "="*80)
    print("CLEANUP RECOMMENDATIONS")
    print("="*80)
    
    print(f"\nValid sweeps to KEEP: {len(valid_sweeps)}")
    for sweep in valid_sweeps:
        print(f"  ✓ {sweep['name']} ({sweep['valid_files']} valid files, {sweep['total_size_kb']} KB)")
    
    print(f"\nInvalid sweeps to CLEAN: {len(invalid_sweeps)}")
    for sweep in invalid_sweeps:
        reason = "malformed JSON or inadequate time horizon" if sweep['invalid_files'] > 0 else "inadequate time horizon"
        print(f"  ✗ {sweep['name']} - {reason} ({sweep['invalid_files']} invalid files, {sweep['total_size_kb']} KB)")
    
    print(f"\nStorage to reclaim: ~{sum(s['total_size_kb'] for s in invalid_sweeps)} KB")
    
    print("\nRecommended actions:")
    print("  1. Keep scientifically valid sweeps (with adequate time horizons)")
    print("  2. Remove invalid sweeps with inadequate time periods")
    print("  3. Regenerate critical results with proper time horizons (≥3600s)")
    print("  4. Document the cleanup for reproducibility")


