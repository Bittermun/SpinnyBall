def main():
    """Main function to analyze and recommend cleanup."""
    print("Analyzing sweep results for scientific validity...")
    
    base_path = Path(".")
    results = identify_invalid_sweeps(base_path)
    
    invalid_sweeps = results['invalid_sweeps']
    valid_sweeps = results['valid_sweeps']
    
    recommend_cleanup_actions(invalid_sweeps, valid_sweeps)
    create_cleanup_script(invalid_sweeps)
    
    print(f"\nSUMMARY:")
    print(f"  - {len(valid_sweeps)} scientifically valid sweep directories to keep")
    print(f"  - {len(invalid_sweeps)} scientifically invalid sweep directories identified for removal")
    print(f"  - Potential storage savings: ~{sum(s['total_size_kb'] for s in invalid_sweeps)} KB")
    
    print(f"\nNext steps:")
    print(f"  1. Review the autogenerated cleanup script")
    print(f"  2. Run high-fidelity sweeps with proper time horizons (≥3600s)")
    print(f"  3. Validate new results meet scientific standards")


if __name__ == "__main__":
    main()